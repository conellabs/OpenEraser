// Shared vocabulary generation, used by both gen-vocab.ts (standalone) and
// build-artifact.ts (as part of `npm run build`). Single source of truth for
// the agent-facing icon list — never hand-maintain a copy.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { iconManifest } from '../src/icons.js';

export function writeVocab(root: string): string {
  const lines = iconManifest.map((d) => `- \`${d.name}\` — ${d.description}`);

  const md = `<!-- GENERATED by open-eraser (npm run build / npm run gen-vocab) — do not edit by hand. -->

## Diagram icon vocabulary

When emitting Mermaid diagrams, you may annotate nodes and subgraphs with
icons using comment directives. Place them anywhere in the diagram:

\`\`\`
%% icons: NODE_ID=icon-name, OTHER_ID=icon-name
\`\`\`

Use only the icon names below. Pick the name whose *meaning* best matches the
component — never invent names. Nodes without a fitting icon may simply be
left un-annotated; they render as clean labeled blocks.

${lines.join('\n')}
`;

  const outDir = join(root, 'generated');
  mkdirSync(outDir, { recursive: true });
  const out = join(outDir, 'icon-vocabulary.md');
  writeFileSync(out, md);
  return out;
}
